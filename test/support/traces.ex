defmodule Readability.Test.Traces do
  @moduledoc """
  Golden traces of Readability.js, generated by `scripts/traces.sh` into `tmp/traces/` (see
  `scripts/traces/README.md` for the format).

  Traces are not committed, so tests that use them must be tagged `@tag :traces` (or
  `@moduletag :traces`); `test_helper.exs` excludes the tag when no traces exist.

  Trees are converted to the internal node shape of the 1.0 design (§2.1): elements are
  `{tag, attrs, children, nil}` with attributes in DOM order, text nodes are binaries.

  Paths: in the JSON they're child-index paths from the document, root first (`[0, 1, 3]` is
  `document.childNodes[0].childNodes[1].childNodes[3]`). `attempts/1` reverses them to the
  design's `[i_n, …, i_0]` form (nearest index first), so they compare directly with paths
  built as `[i | parent_path]`.
  """

  @root Path.expand("../..", __DIR__)

  @inputs %{jsdomparser: "tmp/traces", lexbor: "tmp/traces/lexbor"}

  @doc_tree_keys ~w(input prepped)
  @node_tree_keys ~w(before_post_process after_post_process)
  @attempt_doc_tree_keys ~w(start post_walk)
  @attempt_node_tree_keys ~w(article_pre_prep article_post_prep article)

  @doc """
  Directory holding the traces for `input`: `:jsdomparser` (the default, Readability.js on
  JSDOMParser exactly as upstream's tests run it) or `:lexbor` (Readability.js on LazyHTML's tree).
  """
  def dir(input \\ :jsdomparser), do: Path.join(@root, Map.fetch!(@inputs, input))

  @doc "Whether any traces have been generated (see `missing/1` for full coverage)."
  def available?(input \\ :jsdomparser), do: pages(input) != []

  @doc """
  The test pages (`test/fixtures/readability_js/pages`) that have no trace for `input`, sorted.
  `test_helper.exs` enables the `:traces` tag only when this is empty for both inputs.
  """
  def missing(input \\ :jsdomparser) do
    all = @root |> Path.join("test/fixtures/readability_js/pages") |> File.ls!() |> Enum.sort()
    all -- pages(input)
  end

  @doc "Pages with a trace, sorted."
  def pages(input \\ :jsdomparser) do
    case File.ls(dir(input)) do
      {:ok, files} -> for(f <- files, String.ends_with?(f, ".json"), do: Path.rootname(f)) |> Enum.sort()
      {:error, _} -> []
    end
  end

  @doc "Loads the raw trace of `page` (string keys, `null` as `nil`)."
  def load(page, input \\ :jsdomparser) do
    json = File.read!(Path.join(dir(input), page <> ".json"))
    {value, :ok, ""} = :json.decode(json, :ok, %{null: nil})
    value
  end

  @doc """
  Converts the tree stored under `key` of a trace (or of an attempt map from the raw trace).

  Document trees (`"input"`, `"prepped"`, an attempt's `"start"` and `"post_walk"`) become a list
  of nodes; article trees (`"article*"`, `"before_post_process"`, `"after_post_process"`) a single
  element.
  """
  def tree(trace, key) when is_map(trace) do
    case Map.fetch!(trace, key) do
      nil -> nil
      list when key in @doc_tree_keys or key in @attempt_doc_tree_keys -> to_tree(list)
      node when key in @node_tree_keys or key in @attempt_node_tree_keys -> to_node(node)
    end
  end

  @doc """
  The attempts (passes of `_grabArticle`'s loop) with trees converted, paths reversed (see the
  moduledoc) and scores as floats. Keys are the JSON keys.
  """
  def attempts(trace) do
    for attempt <- trace["attempts"] do
      attempt
      |> convert_trees(@attempt_doc_tree_keys, &to_tree/1)
      |> convert_trees(@attempt_node_tree_keys, &to_node/1)
      |> Map.update!("elements_to_score_paths", fn paths -> Enum.map(paths, &rpath/1) end)
      |> update_present("candidates", fn cs -> Enum.map(cs, &candidate/1) end)
      |> update_present("top_candidates", fn cs -> Enum.map(cs, &candidate/1) end)
      |> update_present("top_candidate", &candidate/1)
      |> update_present("parent_of_top_candidate", &rpath/1)
      |> update_present("appended_siblings", fn ss -> Enum.map(ss, &Map.update!(&1, "path", fn p -> rpath(p) end)) end)
    end
  end

  defp convert_trees(map, keys, fun), do: Enum.reduce(keys, map, &update_present(&2, &1, fun))

  defp update_present(map, key, fun) do
    case map do
      %{^key => nil} -> map
      %{^key => value} -> %{map | key => fun.(value)}
      %{} -> map
    end
  end

  defp candidate(c) do
    c
    |> Map.update!("path", &rpath/1)
    |> Map.update!("score", &float/1)
    |> update_present("final_score", &float/1)
  end

  defp rpath(nil), do: nil
  defp rpath(path), do: Enum.reverse(path)

  # JSON.stringify writes integral doubles without a fraction; scores are always doubles in JS.
  defp float(x) when is_integer(x), do: x * 1.0
  defp float(x) when is_float(x), do: x

  @doc "Converts a dumped document tree (a JSON list of nodes)."
  def to_tree(nodes) when is_list(nodes), do: Enum.map(nodes, &to_node/1)

  @doc "Converts one dumped node: `[tag, [[name, value], ...], children]` or a string."
  def to_node(text) when is_binary(text), do: text

  def to_node([tag, attrs, children]),
    do: {tag, Enum.map(attrs, fn [name, value] -> {name, value} end), to_tree(children), nil}

  @doc """
  The reference conversion of a `LazyHTML.to_tree/1` result to the node shape: comments dropped,
  `<template>` made childless (design §4.2), stats `nil`. Used by `scripts/parser_parity.exs`.
  """
  def from_lazy(nodes) when is_list(nodes) do
    for node <- nodes, not match?({:comment, _}, node), do: from_lazy_node(node)
  end

  defp from_lazy_node(text) when is_binary(text), do: text
  defp from_lazy_node({"template", attrs, _children}), do: {"template", attrs, [], nil}
  defp from_lazy_node({tag, attrs, children}), do: {tag, attrs, from_lazy(children), nil}

  @doc """
  Compares two trees (lists of nodes) or two nodes exactly: tags, attributes in order, text
  byte for byte, children counts. The 4th element slot (stats) is ignored, and 3-tuples are
  accepted as well. `nil` (e.g. a trace's missing article) equals only `nil`.

  Returns `:ok` or `{:diff, description}` for the first difference in document order, where the
  description names the location as a `tag[index]` chain from the compared root and shows both
  sides.
  """
  def diff_trees(nil, nil), do: :ok
  def diff_trees(nil, expected), do: {:diff, "at root: nothing vs #{summary_any(expected)} expected"}
  def diff_trees(actual, nil), do: {:diff, "at root: #{summary_any(actual)} vs nothing expected"}

  def diff_trees(actual, expected) do
    case diff(List.wrap(actual), List.wrap(expected), []) do
      :ok -> :ok
      {:diff, location, what} -> {:diff, "at #{format_location(location)}: #{what}"}
    end
  end

  defp diff([], [], _loc), do: :ok

  defp diff(actual, expected, loc) when length(actual) != length(expected) do
    {:diff, loc,
     "#{length(actual)} children vs #{length(expected)} expected\n" <>
       "  actual:   #{summary_list(actual)}\n  expected: #{summary_list(expected)}" <>
       first_child_diff(actual, expected)}
  end

  defp diff(actual, expected, loc) do
    actual
    |> Enum.zip(expected)
    |> Enum.with_index()
    |> Enum.reduce_while(:ok, fn {{a, e}, i}, :ok ->
      case diff_node(a, e, [{label(e), i} | loc]) do
        :ok -> {:cont, :ok}
        diff -> {:halt, diff}
      end
    end)
  end

  # Where the counts differ, also point at the first differing child, which usually explains it.
  defp first_child_diff(actual, expected) do
    case Enum.find_index(Enum.zip(actual, expected), fn {a, e} -> diff_node(a, e, []) != :ok end) do
      nil -> ""
      i -> "\n  first differing child: ##{i}: #{summary(Enum.at(actual, i))} vs #{summary(Enum.at(expected, i))}"
    end
  end

  defp diff_node(text, text, _loc) when is_binary(text), do: :ok

  defp diff_node(a, e, loc) when is_binary(a) and is_binary(e),
    do: {:diff, loc, "text differs\n  actual:   #{inspect_text(a, e)}\n  expected: #{inspect_text(e, a)}"}

  defp diff_node(a, e, loc) when is_tuple(a) and is_tuple(e) do
    {atag, aattrs, achildren} = parts(a)
    {etag, eattrs, echildren} = parts(e)

    cond do
      atag != etag ->
        {:diff, loc, "tag #{inspect(atag)} vs #{inspect(etag)} expected"}

      aattrs != eattrs ->
        {:diff, loc, "attributes differ\n  actual:   #{inspect(aattrs)}\n  expected: #{inspect(eattrs)}"}

      true ->
        diff(achildren, echildren, loc)
    end
  end

  defp diff_node(a, e, loc), do: {:diff, loc, "#{summary(a)} vs #{summary(e)} expected"}

  defp parts({tag, attrs, children}), do: {tag, attrs, children}
  defp parts({tag, attrs, children, _stats}), do: {tag, attrs, children}

  defp label(text) when is_binary(text), do: "#text"
  defp label(el), do: el |> parts() |> elem(0)

  defp format_location([]), do: "root"
  defp format_location(loc), do: loc |> Enum.reverse() |> Enum.map_join(" > ", fn {l, i} -> "#{l}[#{i}]" end)

  defp summary_list(nodes) when length(nodes) > 12,
    do: (nodes |> Enum.take(12) |> Enum.map_join(", ", &summary/1)) <> ", …"

  defp summary_list(nodes), do: Enum.map_join(nodes, ", ", &summary/1)

  defp summary_any(nodes) when is_list(nodes), do: "[#{summary_list(nodes)}]"
  defp summary_any(node), do: summary(node)

  defp summary(nil), do: "(nothing)"
  defp summary(text) when is_binary(text), do: inspect(truncate(text, 40))

  defp summary(el) do
    {tag, attrs, children} = parts(el)
    attrs = Enum.map_join(attrs, "", fn {k, v} -> " #{k}=#{inspect(truncate(v, 30))}" end)
    "<#{tag}#{attrs}>(#{length(children)})"
  end

  defp truncate(s, n) when byte_size(s) <= n, do: s
  defp truncate(s, n), do: binary_part(s, 0, n) <> "…"

  # Shows the text around the first differing byte.
  defp inspect_text(s, other) do
    prefix = :binary.longest_common_prefix([s, other])
    start = max(prefix - 30, 0)
    window = binary_part(s, start, min(byte_size(s) - start, 80))
    "#{inspect(window, binaries: :as_strings)} (#{byte_size(s)} bytes, first difference at byte #{prefix})"
  end
end
